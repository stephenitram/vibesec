import json
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Dict, Any, Optional

from src.schemas import Vulnerability
from src.sca import DependencyVulnerability


def generate_sarif_report(
    vulnerabilities: List[Vulnerability],
    sca_findings: Optional[List[DependencyVulnerability]] = None,
    tool_name: str = "VibeSec-Local",
    tool_version: str = "2.0.0",
) -> Dict[str, Any]:
    """Generate standard SARIF 2.1.0 JSON format for GitHub / GitLab / SonarQube CI integration."""
    rules_map: Dict[str, Dict[str, Any]] = {}
    results = []

    for v in vulnerabilities:
        rule_id = v.cwe_id
        if rule_id not in rules_map:
            rules_map[rule_id] = {
                "id": rule_id,
                "name": v.title,
                "shortDescription": {"text": v.title},
                "fullDescription": {"text": v.explanation},
                "defaultConfiguration": {
                    "level": "error" if v.severity.value in ["CRITICAL", "HIGH"] else "warning"
                },
                "helpUri": f"https://cwe.mitre.org/data/definitions/{rule_id.replace('CWE-', '')}.html",
            }

        level = "error" if v.severity.value in ["CRITICAL", "HIGH"] else "warning"
        results.append({
            "ruleId": rule_id,
            "level": level,
            "message": {
                "text": f"[{v.cwe_id}] {v.title}: {v.explanation}"
            },
            "locations": [
                {
                    "physicalLocation": {
                        "artifactLocation": {
                            "uri": v.file_path.replace("\\", "/")
                        },
                        "region": {
                            "startLine": v.line_number or 1,
                            "snippet": {
                                "text": v.original_code
                            }
                        }
                    }
                }
            ],
            "fixes": [
                {
                    "description": {
                        "text": "Automated remediation generated by VibeSec AI"
                    },
                    "replacement": v.remediation_patch
                }
            ]
        })

    if sca_findings:
        for sca in sca_findings:
            rule_id = sca.cve_id
            if rule_id not in rules_map:
                rules_map[rule_id] = {
                    "id": rule_id,
                    "name": f"Vulnerable Dependency ({sca.package_name})",
                    "shortDescription": {"text": sca.title},
                    "fullDescription": {"text": sca.description},
                    "defaultConfiguration": {
                        "level": "error" if sca.severity.value in ["CRITICAL", "HIGH"] else "warning"
                    },
                    "helpUri": f"https://nvd.nist.gov/vuln/detail/{sca.cve_id}",
                }

            results.append({
                "ruleId": rule_id,
                "level": "error" if sca.severity.value in ["CRITICAL", "HIGH"] else "warning",
                "message": {
                    "text": f"[{sca.cve_id}] {sca.package_name}@{sca.installed_version} is vulnerable. Upgrade to >={sca.safe_version}."
                },
                "locations": [
                    {
                        "physicalLocation": {
                            "artifactLocation": {
                                "uri": sca.manifest_file.replace("\\", "/")
                            }
                        }
                    }
                ]
            })

    sarif_doc = {
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": tool_name,
                        "version": tool_version,
                        "informationUri": "https://github.com/vibesec/vibesec-local",
                        "rules": list(rules_map.values()),
                    }
                },
                "results": results,
            }
        ]
    }

    return sarif_doc


def generate_executive_markdown_report(
    repo_path: Path,
    vulnerabilities: List[Vulnerability],
    sca_findings: Optional[List[DependencyVulnerability]] = None,
    health_score: int = 100,
) -> str:
    """Generate a formal Academic & Executive Cybersecurity Audit Report in Markdown."""
    sca_list = sca_findings or []
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    crit = sum(1 for v in vulnerabilities if v.severity.value == "CRITICAL")
    high = sum(1 for v in vulnerabilities if v.severity.value == "HIGH")
    med = sum(1 for v in vulnerabilities if v.severity.value == "MEDIUM")
    low = sum(1 for v in vulnerabilities if v.severity.value == "LOW")

    crit_sca = sum(1 for s in sca_list if s.severity.value == "CRITICAL")
    high_sca = sum(1 for s in sca_list if s.severity.value == "HIGH")

    report = f"""# VibeSec Cybersecurity & Code Audit Report
**Workspace:** `{repo_path.name}` (`{repo_path.resolve()}`)  
**Generated Date:** `{timestamp}`  
**Audit Standard:** OWASP Top 10 (2021), MITRE CWE Top 25, NIST SP 800-218 (SSDF)  
**Security Health Score:** `{health_score}%`

---

## 1. Executive Summary
This automated security audit evaluates application source code and third-party software supply chain manifests against contemporary cybersecurity threat models. With the acceleration of AI-assisted software generation ("Vibe Coding"), automated pre-commit static analysis and local LLM verification ensure that hallucinated sinks, hardcoded secrets, and outdated dependencies are intercepted prior to deployment.

### Risk Summary Table
| Metric | SAST (Source Code) | SCA (Supply Chain) | Total Findings |
| :--- | :--- | :--- | :--- |
| **Critical** | {crit} | {crit_sca} | {crit + crit_sca} |
| **High** | {high} | {high_sca} | {high + high_sca} |
| **Medium** | {med} | 0 | {med} |
| **Low** | {low} | 0 | {low} |
| **Total Flaws** | **{len(vulnerabilities)}** | **{len(sca_list)}** | **{len(vulnerabilities) + len(sca_list)}** |

---

## 2. Static Application Security Testing (SAST) Findings
"""

    if not vulnerabilities:
        report += "\n> [!NOTE]\n> **No source code security vulnerabilities detected.** The audited codebase complies with core secure coding standards.\n"
    else:
        for idx, v in enumerate(vulnerabilities, 1):
            report += f"""
### {idx}. [{v.severity.value}] {v.title} (`{v.cwe_id}`)
* **Location:** [`{v.file_path}:{v.line_number or 1}`](file:///{repo_path.resolve() / v.file_path})
* **Vulnerability Description:** {v.explanation}
* **MITRE Taxonomy:** [{v.cwe_id} Definition](https://cwe.mitre.org/data/definitions/{v.cwe_id.replace('CWE-', '')}.html)

```diff
- Insecure Source Code Pattern:
{v.original_code}

+ Secure Remediation (Verified Patch):
{v.remediation_patch}
```
"""

    report += "\n---\n\n## 3. Software Supply Chain & Dependency (SCA) Findings\n"

    if not sca_list:
        report += "\n> [!NOTE]\n> **No vulnerable third-party dependencies identified.** All evaluated package manifests are within secure baseline versions.\n"
    else:
        for idx, sca in enumerate(sca_list, 1):
            report += f"""
### {idx}. [{sca.severity.value}] {sca.package_name}@{sca.installed_version} (`{sca.cve_id}`) — CVSS {sca.cvss_score}
* **Manifest File:** `{sca.manifest_file}`
* **Ecosystem:** `{sca.ecosystem}`
* **Advisory Summary:** {sca.description}
* **Recommended Safe Upgrade:** `{sca.remediation_cmd}`
"""

    report += """
---

## 4. Compliance & AI Risk Mitigation Guidance
1. **Zero-Telemetry Assurance:** All security evaluations were processed locally on-premise without transmitting source code to external servers.
2. **Pre-Commit Enforcement:** Maintain active Git pre-commit hooks (`vibesec hook install`) to prevent non-compliant commits from entering version control.
3. **Continuous Verification:** Run automated test-driven remediation before merging automated security patches.
"""

    return report
