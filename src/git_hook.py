import os
import stat
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional
import git


@dataclass
class StagedHunk:
    file_path: str
    start_line: int
    added_lines: List[str]
    raw_diff: str


def get_git_repo(repo_path: Optional[Path] = None) -> git.Repo:
    """Find and return git.Repo instance for the given or current path."""
    target_path = repo_path or Path.cwd()
    try:
        return git.Repo(target_path, search_parent_directories=True)
    except (git.InvalidGitRepositoryError, git.NoSuchPathError) as e:
        raise RuntimeError(f"Not a valid git repository: {target_path}") from e


def extract_staged_diffs(repo_path: Optional[Path] = None) -> List[StagedHunk]:
    """Parse git diff --cached and extract staged additions per file with line numbers."""
    repo = get_git_repo(repo_path)
    staged_hunks: List[StagedHunk] = []

    # Get cached diff against HEAD (or empty tree if initial commit)
    try:
        if repo.head.is_valid():
            diff_index = repo.head.commit.diff()
        else:
            diff_index = repo.index.diff(git.NULL_TREE)
    except Exception:
        diff_index = repo.index.diff(git.NULL_TREE)

    # Use repo.git.diff('--cached', '-U3') for complete unified diff text
    try:
        cached_diff_text = repo.git.diff("--cached", "-U3")
    except Exception as e:
        return staged_hunks

    if not cached_diff_text.strip():
        return staged_hunks

    # Parse unified diff into hunks
    current_file: Optional[str] = None
    current_start_line = 1
    current_added_lines: List[str] = []
    current_hunk_lines: List[str] = []

    for line in cached_diff_text.splitlines():
        if line.startswith("diff --git"):
            if current_file and (current_added_lines or current_hunk_lines):
                staged_hunks.append(
                    StagedHunk(
                        file_path=current_file,
                        start_line=current_start_line,
                        added_lines=current_added_lines,
                        raw_diff="\n".join(current_hunk_lines),
                    )
                )
            current_file = None
            current_added_lines = []
            current_hunk_lines = []
        elif line.startswith("+++ b/"):
            current_file = line[6:].strip()
        elif line.startswith("@@"):
            if current_file and (current_added_lines or current_hunk_lines):
                staged_hunks.append(
                    StagedHunk(
                        file_path=current_file,
                        start_line=current_start_line,
                        added_lines=current_added_lines,
                        raw_diff="\n".join(current_hunk_lines),
                    )
                )
            current_added_lines = []
            current_hunk_lines = [line]
            # Parse @@ -a,b +c,d @@
            parts = line.split("@@")
            if len(parts) >= 2:
                range_info = parts[1].strip()
                plus_part = [p for p in range_info.split() if p.startswith("+")]
                if plus_part:
                    nums = plus_part[0][1:].split(",")
                    try:
                        current_start_line = int(nums[0])
                    except ValueError:
                        current_start_line = 1
        elif current_file:
            current_hunk_lines.append(line)
            if line.startswith("+") and not line.startswith("+++"):
                current_added_lines.append(line[1:])

    if current_file and (current_added_lines or current_hunk_lines):
        staged_hunks.append(
            StagedHunk(
                file_path=current_file,
                start_line=current_start_line,
                added_lines=current_added_lines,
                raw_diff="\n".join(current_hunk_lines),
            )
        )

    return staged_hunks


def get_pre_commit_script(python_exe: str) -> str:
    # Normalize path with forward slashes for bash compatibility
    norm_python = python_exe.replace("\\", "/")
    return f"""#!/usr/bin/env bash
# VibeSec-Local Pre-Commit Hook
# Auto-generated by vibesec install

# 1. Try explicit python environment used during installation
if [ -f "{norm_python}" ]; then
    "{norm_python}" -m src.cli scan --staged
    EXIT_CODE=$?
# 2. Try vibesec from virtual environment if present or global PATH
elif [ -f "./venv/Scripts/vibesec.exe" ]; then
    ./venv/Scripts/vibesec.exe scan --staged
    EXIT_CODE=$?
elif [ -f "./venv/bin/vibesec" ]; then
    ./venv/bin/vibesec scan --staged
    EXIT_CODE=$?
elif command -v vibesec >/dev/null 2>&1; then
    vibesec scan --staged
    EXIT_CODE=$?
else
    # 3. Fallback to global python
    python -m src.cli scan --staged
    EXIT_CODE=$?
fi

if [ $EXIT_CODE -ne 0 ]; then
    echo ""
    echo "[VibeSec-Local] Commit rejected due to unresolved security vulnerabilities."
    echo "Fix the flagged code or run 'vibesec scan --staged' to inspect and remediate."
    exit 1
fi

exit 0
"""


def install_hook(repo_path: Optional[Path] = None) -> Path:
    """Install the pre-commit hook into .git/hooks/pre-commit."""
    repo = get_git_repo(repo_path)
    hooks_dir = Path(repo.git_dir) / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    hook_file = hooks_dir / "pre-commit"

    script_content = get_pre_commit_script(sys.executable)
    with open(hook_file, "w", encoding="utf-8", newline="\n") as f:
        f.write(script_content)

    # Set executable permissions
    try:
        current_perms = os.stat(hook_file).st_mode
        os.chmod(hook_file, current_perms | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except Exception:
        pass

    return hook_file


def uninstall_hook(repo_path: Optional[Path] = None) -> bool:
    """Uninstall the pre-commit hook."""
    repo = get_git_repo(repo_path)
    hook_file = Path(repo.git_dir) / "hooks" / "pre-commit"
    if hook_file.exists():
        hook_file.unlink()
        return True
    return False
